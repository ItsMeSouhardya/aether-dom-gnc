import { expect, test } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';

test('reviews saved hotspots and opens portable details without API writes', async ({ page, request }, info) => {
  test.setTimeout(90000);
  const snapshot = await (await request.get('/api/v1/projects/proj_neon_shogun/branches/branch_main/document')).json();
  const branch = `lore_${info.project.name}`;
  expect((await request.post('/api/v1/projects/proj_neon_shogun/branches', { data: { commandId: `fork_${branch}`, op: 'forkBranch', projectId: 'proj_neon_shogun', sourceBranchId: 'branch_main', expectedRevision: snapshot.document.project.revision, newBranchId: branch, name: branch, actor: { kind: 'human', id: 'test' }, reason: 'Isolate lore test' } })).ok()).toBe(true);
  const markup = '<img src=x onerror=alert(1)> saved as text';
  expect((await request.post(`/api/v1/projects/proj_neon_shogun/branches/${branch}/commands`, { data: { commandId: `recovery_${branch}`, op: 'recordConstraintRecovery', projectId: 'proj_neon_shogun', branchId: branch, expectedRevision: snapshot.document.project.revision, targetId: 'constraint_kael_left_arm', args: { eventId: `event_lore_${info.project.name}`, sceneId: 'scene_rooftop', order: 2, description: markup }, actor: { kind: 'human', id: 'test' }, reason: 'Save text evidence' } })).ok()).toBe(true);
  await page.goto(`/studio?projectId=proj_neon_shogun&branchId=${branch}`);
  await page.getByRole('button', { name: 'Add hotspot' }).click();
  await page.getByLabel('Label', { exact: true }).fill('Cancelled');
  await page.getByRole('button', { name: 'Cancel hotspot draft' }).click();
  await expect(page.getByText('Cancelled', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Add hotspot' }).click();
  await page.getByLabel('Label', { exact: true }).fill('Saved lore');
  await page.getByLabel('16:9 X %').fill('0'); await page.getByLabel('9:16 Y %').fill('100');
  await page.getByRole('button', { name: 'Review hotspot change' }).click();
  await page.screenshot({ path: `.impeccable/review/task12-lore-review-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Save hotspot change' }).click();
  await expect(page.getByRole('status', { name: 'Save status' })).toContainText('Saved locally');
  await page.reload(); await expect(page.getByText('Saved lore', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Review hotspot change' })).toBeDisabled();
  await page.getByRole('button', { name: 'Cancel hotspot draft' }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByText('Saved lore', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(page.getByText('Saved lore', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete', exact: true }).first().click();
  await page.getByRole('button', { name: 'Review hotspot change' }).click();
  await page.getByRole('button', { name: 'Save hotspot change' }).click();
  await expect(page.getByText('Saved lore', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByText('Saved lore', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  const exporter = page.getByRole('complementary', { name: 'Export JSON inspector' });
  await exporter.getByRole('button', { name: 'Review export' }).click();
  const downloading = page.waitForEvent('download'); await exporter.getByRole('button', { name: 'Download JSON' }).click();
  const file = info.outputPath('lore.json'); await (await downloading).saveAs(file);
  await page.goto('/player'); await page.getByLabel('Open local player JSON').setInputFiles(file);
  let writes = 0;
  await page.route('**/api/**', route => { if (route.request().method() !== 'GET') writes++; return route.abort(); });
  for (const aspect of ['16:9', '9:16']) {
    await page.getByLabel('Player aspect ratio').selectOption(aspect);
    const marker = page.getByRole('button', { name: 'Lore: Saved lore' }); await marker.click();
    const bounds = await marker.boundingBox(), frame = await page.getByRole('group', { name: 'Player stage' }).boundingBox();
    expect(bounds!.width).toBeGreaterThanOrEqual(44); expect(bounds!.height).toBeGreaterThanOrEqual(44);
    expect(bounds!.x).toBeGreaterThanOrEqual(frame!.x - 1); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(frame!.x + frame!.width + 1);
    expect(bounds!.y).toBeGreaterThanOrEqual(frame!.y - 1); expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(frame!.y + frame!.height + 1);
    const details = page.getByRole('complementary', { name: 'Lore details' });
    await expect(details).toContainText('Evidence:'); await expect(details).toContainText('Saved revision');
    await expect(details).toContainText(markup); await expect(details.locator('img')).toHaveCount(0);
    await expect(details).toContainText('constraint_kael_left_arm'); await expect(details).toContainText(`event_lore_${info.project.name}`);
    await page.screenshot({ path: `.impeccable/review/task12-lore-player-${info.project.name}-${aspect.replace(':', '-')}.png`, fullPage: true });
    await page.keyboard.press('Escape'); await expect(marker).toBeFocused();
  }
  expect(writes).toBe(0);
  const dangling = JSON.parse(await readFile(file, 'utf8'));
  dangling.document.shots.find((shot: { hotspots?: unknown[] }) => shot.hotspots?.length).hotspots[0].targetId = 'missing_target';
  const missingFile = info.outputPath('missing.json'); await writeFile(missingFile, JSON.stringify(dangling));
  await page.getByLabel('Open local player JSON').setInputFiles(missingFile);
  await page.getByRole('button', { name: 'Lore: Saved lore' }).click();
  await expect(page.getByRole('complementary', { name: 'Lore details' })).toContainText('missing_target');
  await expect(page.getByRole('complementary', { name: 'Lore details' })).toContainText('Open a corrected saved JSON file');
  await expect(page.getByRole('complementary', { name: 'Lore details' })).toContainText('studio that owns it');
  expect(writes).toBe(0);
});

test('retains an uncertain draft during a slow save and permits cancel recovery', async ({ page, request }, info) => {
  const snapshot = await (await request.get('/api/v1/projects/proj_neon_shogun/branches/branch_main/document')).json();
  const branch = `lore_recovery_${info.project.name}`;
  expect((await request.post('/api/v1/projects/proj_neon_shogun/branches', { data: { commandId: `fork_${branch}`, op: 'forkBranch', projectId: 'proj_neon_shogun', sourceBranchId: 'branch_main', expectedRevision: snapshot.document.project.revision, newBranchId: branch, name: branch, actor: { kind: 'human', id: 'test' }, reason: 'Isolate recovery test' } })).ok()).toBe(true);
  await page.goto(`/studio?projectId=proj_neon_shogun&branchId=${branch}`);
  await page.getByRole('button', { name: 'Add hotspot' }).click();
  await page.getByLabel('Label', { exact: true }).fill('Keep this draft');
  await page.getByRole('button', { name: 'Review hotspot change' }).click();
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/commands', async route => { await gate; await route.abort(); });
  await page.getByRole('button', { name: 'Save hotspot change' }).click();
  await expect(page.getByLabel('Label', { exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Cancel hotspot draft' })).toBeDisabled();
  await expect(page.getByText('Player', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByText('Seed overview', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  release();
  await expect(page.getByRole('alert', { name: 'Save status' })).toContainText('unknown');
  await expect(page.getByLabel('Label', { exact: true })).toHaveValue('Keep this draft');
  await expect(page.getByRole('button', { name: 'Reload latest' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Reload document' })).toBeDisabled();
  await expect(page.getByText('Player', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByText('Seed overview', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByRole('link', { name: 'Player', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Seed overview', exact: true })).toHaveCount(0);
  await expect(page.getByText('Copy any draft values you need, then cancel this draft to enable Reload latest.')).toBeVisible();
  await page.getByRole('button', { name: 'Cancel hotspot draft' }).click();
  await expect(page.getByLabel('Label', { exact: true })).toHaveCount(0);
  await expect(page.getByText('Player', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByRole('button', { name: 'Reload latest' })).toBeEnabled();
  await page.getByRole('button', { name: 'Reload latest' }).click();
  await expect(page.getByRole('button', { name: 'Add hotspot' })).toBeEnabled();
  await expect(page.getByRole('link', { name: 'Player', exact: true })).toBeVisible();
});

test('conflict keeps the draft until cancel, then allows reload', async ({ page, request }, info) => {
  const snapshot = await (await request.get('/api/v1/projects/proj_neon_shogun/branches/branch_main/document')).json();
  const branch = `lore_conflict_${info.project.name}`;
  expect((await request.post('/api/v1/projects/proj_neon_shogun/branches', { data: { commandId: `fork_${branch}`, op: 'forkBranch', projectId: 'proj_neon_shogun', sourceBranchId: 'branch_main', expectedRevision: snapshot.document.project.revision, newBranchId: branch, name: branch, actor: { kind: 'human', id: 'test' }, reason: 'Isolate conflict recovery' } })).ok()).toBe(true);
  await page.goto(`/studio?projectId=proj_neon_shogun&branchId=${branch}`);
  await page.getByRole('button', { name: 'Add hotspot' }).click();
  await page.getByLabel('Label', { exact: true }).fill('Conflict draft');
  await page.getByRole('button', { name: 'Review hotspot change' }).click();
  await page.route('**/commands', route => route.fulfill({ status: 409, contentType: 'application/json', body: '{}' }));
  await page.getByRole('button', { name: 'Save hotspot change' }).click();
  await expect(page.getByRole('alert', { name: 'Save status' })).toContainText('Reload latest');
  await expect(page.getByLabel('Label', { exact: true })).toHaveValue('Conflict draft');
  await expect(page.getByRole('button', { name: 'Reload latest' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Reload document' })).toBeDisabled();
  await expect(page.getByText('Player', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByText('Seed overview', { exact: true })).toHaveAttribute('aria-disabled', 'true');
  await page.getByRole('button', { name: 'Cancel hotspot draft' }).click();
  await page.getByRole('button', { name: 'Reload latest' }).click();
  await expect(page.getByRole('button', { name: 'Add hotspot' })).toBeEnabled();
});

