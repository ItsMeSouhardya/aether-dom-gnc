const main = '/api/v1/projects/proj_neon_shogun/branches/branch_main';
async function fork(request: APIRequestContext, id: string) {
  const snapshot = await (await request.get(`${main}/document`)).json();
  const payload = { commandId: `fork_${id}`, op: 'forkBranch', projectId: 'proj_neon_shogun', sourceBranchId: 'branch_main', expectedRevision: snapshot.document.project.revision, newBranchId: id, name: id, actor: { kind: 'human', id: 'test' }, reason: 'Isolate rights test' };
  expect((await request.post('/api/v1/projects/proj_neon_shogun/branches', { data: payload })).ok()).toBe(true);
  return `/api/v1/projects/proj_neon_shogun/branches/${id}`;
}
