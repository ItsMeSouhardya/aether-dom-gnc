import { cp, mkdir, rm } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(project, 'dist');
if (dirname(output) !== project || output !== resolve(project, 'dist')) throw new Error('Build output must be the project dist directory');
console.log(`Rebuilding generated output: ${output}`);
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(resolve(project, 'landing-page'), output, { recursive: true });
console.log('Built Afterlight v2 in dist/. Archived designs are excluded.');
