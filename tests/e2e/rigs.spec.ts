test('clears a legacy transform draft when selection changes without writing either layer', async ({ page, request }, info) => {
  const branch = `rig_legacy_selection_${info.project.name}`, base = await fork(request, branch);
  const before = await (await request.get(`${base}/document`)).json();
  const target = before.document.layers.find((layer: { id: string }) => layer.id === 'layer_vance');
  let writes = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/commands')) writes++; });
  await page.goto(`/studio?projectId=proj_neon_shogun&branchId=${branch}`);
  const navigator = page.getByRole('navigation', { name: 'Layer navigator' });
  await navigator.getByRole('button', { name: 'Select layer Kael', exact: true }).click();
  await page.getByRole('button', { name: 'Edit transform', exact: true }).click();
  await page.getByLabel('Edit X position', { exact: true }).fill('13');
  await navigator.getByRole('button', { name: 'Select layer Vance', exact: true }).click();
  await expect(page.getByRole('form', { name: 'Edit layer transform' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Save transform', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit transform', exact: true }).click();
  await expect(page.getByLabel('Edit X position', { exact: true })).toHaveValue(String(target.transform.x));
  await expect(page.getByRole('button', { name: 'Save transform', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Cancel transform edit', exact: true }).click();
  expect(writes).toBe(0);
  expect((await (await request.get(`${base}/document`)).json()).document).toEqual(before.document);
});

