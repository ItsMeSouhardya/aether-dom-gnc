test('freezes all evidence draft controls until a delayed successful save returns', async ({ page, request }, testInfo) => {
  const branch = `rights_delayed_${testInfo.project.name}`, base = await fork(request, branch);
  const before = await (await request.get(`${base}/document`)).json();
  await page.goto(`/studio?projectId=proj_neon_shogun&branchId=${branch}`);
  await page.getByText('Asset references', { exact: false }).click();
  await page.getByRole('button', { name: /Review evidence/ }).first().click();
  const panel = page.getByRole('region', { name: 'Asset evidence inspector' });
  await panel.getByRole('button', { name: 'Edit evidence' }).click();
  await panel.getByRole('textbox', { name: 'Creator', exact: true }).fill('Captured creator');
  await panel.getByRole('button', { name: 'Add evidence' }).click();
  await panel.getByLabel('Evidence label').fill('Statement');
  await panel.getByLabel('Evidence text').fill('Captured evidence text.');
  await panel.getByRole('button', { name: 'Review changes' }).click();
  let release!: () => void, received!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const committed = new Promise<void>(resolve => { received = resolve; });
  await page.route('**/commands', async route => {
    const response = await route.fetch(); received(); await gate; await route.fulfill({ response });
  });
  try {
    await panel.getByRole('button', { name: 'Save evidence' }).click();
    await committed;
    const controls = panel.locator('.lore-editor').locator('input, textarea, select, button');
    expect(await controls.count()).toBeGreaterThan(10);
    for (const control of await controls.all()) await expect(control).toBeDisabled();
    await expect(panel.getByRole('textbox', { name: 'Creator', exact: true })).toHaveValue('Captured creator');
  } finally { release(); }
  await expect(page.getByRole('status', { name: 'Save status' })).toContainText('Saved locally');
  const after = await (await request.get(`${base}/document`)).json();
  expect(after.document.project.revision).toBe(before.document.project.revision + 1);
  expect(after.document.assets[0].provenance.creator).toBe('Captured creator');
});

